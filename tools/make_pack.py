#!/usr/bin/env python3
"""Build a Rhythm Heaven data pack for touchable-ohos.

The project does not ship game data. This tool assembles a pack from files you
already extracted from your own copy of the game:

  mods/          rewritten code modules (main.* / sdk.* from nx2android)
  RomFS/         the game's RomFS
  shaders.dmsv   Vulkan shader bundle for THIS game/profile
  nx2a-data.json generated by this script
  env.txt        generated by this script
  optional: aoc/, sysdata/, standard.ttf, nintendo_ext.ttf, settings.txt

Pass --zip to also write a single .zip archive of the pack. The app imports it with
"UI -> 导入数据包（ZIP）" and unpacks it into its sandbox (no folder copy on the phone).

Example:

  python3 tools/make_pack.py \
      --romfs /path/to/RomFS \
      --mods /path/to/mods \
      --shaders /path/to/shaders.dmsv \
      --out /path/to/game-pack

The output folder is what the app's "导入数据包" picker expects.
"""
import argparse
import json
import os
import shutil
import time
import zipfile
from pathlib import Path

TITLE_ID = '0100D9F01D474000'
NAME = 'Rhythm Heaven Groove'
PACKAGE = 'com.nx2a.rhythm'
MANIFEST = 'nx2a-data.json'


def link_or_copy(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def copy_tree(src: Path, dst: Path):
    n = size = 0
    for root, _, files in os.walk(src):
        for name in files:
            s = Path(root) / name
            link_or_copy(s, dst / s.relative_to(src))
            n += 1
            size += s.stat().st_size
    return n, size


def write_zip(pack: Path, zip_path: Path) -> None:
    """Archive the pack with the pack layout at the zip root (mods/, RomFS/, nx2a-data.json, ...).

    The app's zlib.decompressFile() unpacks it; entries are written with forward slashes and the
    declaration order is sorted so the same pack gives the same archive.
    """
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    if zip_path.exists():
        zip_path.unlink()
    files = sorted((p for p in pack.rglob('*') if p.is_file() and p.name != '.DS_Store'),
                   key=lambda p: p.relative_to(pack).as_posix())
    # Explicit directory entries (name ending in '/'): some unzip implementations only create a directory when
    # they meet its entry, so a files-only archive can fail to unpack nested RomFS paths.
    dirs = set()
    for src in files:
        for parent in src.relative_to(pack).parents:
            if parent.as_posix() != '.':
                dirs.add(parent.as_posix() + '/')
    # Level 1: the RomFS is mostly already-compressed or large; full deflate costs minutes for little gain.
    with zipfile.ZipFile(zip_path, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=1,
                         allowZip64=True) as z:
        for d in sorted(dirs):
            z.writestr(d, b'')
        for src in files:
            z.write(src, src.relative_to(pack).as_posix())
    print(f'archive: {zip_path} ({zip_path.stat().st_size / (1024 ** 2):.0f} MB, {len(files)} entries)')


def require(name: str, p: Path, is_dir: bool):
    if not p.exists():
        raise SystemExit(f'{name} not found: {p}')
    if is_dir and not p.is_dir():
        raise SystemExit(f'{name} must be a directory: {p}')
    if not is_dir and not p.is_file():
        raise SystemExit(f'{name} must be a file: {p}')


def main():
    ap = argparse.ArgumentParser(description='Build a Rhythm Heaven data pack')
    ap.add_argument('--romfs', required=True, type=Path, help='RomFS directory')
    ap.add_argument('--mods', required=True, type=Path, help='rewritten mods directory')
    ap.add_argument('--shaders', required=True, type=Path, help='shaders.dmsv for this core/game')
    ap.add_argument('--out', required=True, type=Path, help='output pack directory')
    ap.add_argument('--aoc', type=Path, help='optional DLC directory')
    ap.add_argument('--sysdata', type=Path, help='optional system data directory')
    ap.add_argument('--standard-font', type=Path, help='optional standard.ttf')
    ap.add_argument('--ext-font', type=Path, help='optional nintendo_ext.ttf')
    ap.add_argument('--lang', default='en-US', help='DM_LANG (default: en-US)')
    ap.add_argument('--version', default='1.0.0')
    ap.add_argument('--display', default=None)
    ap.add_argument('--package', default=PACKAGE)
    ap.add_argument('--force', action='store_true', help='replace an existing output folder')
    ap.add_argument('--zip', type=Path, help='also write a .zip archive of the pack (for the app ZIP import)')
    args = ap.parse_args()

    require('RomFS', args.romfs, True)
    require('mods', args.mods, True)
    require('shaders.dmsv', args.shaders, False)
    if args.aoc:
        require('aoc', args.aoc, True)
    if args.sysdata:
        require('sysdata', args.sysdata, True)
    for label, p in (('standard font', args.standard_font), ('ext font', args.ext_font)):
        if p:
            require(label, p, False)

    out: Path = args.out
    if out.exists():
        if not args.force:
            raise SystemExit(f'output already exists (use --force): {out}')
        shutil.rmtree(out)
    out.mkdir(parents=True)

    total_files = total_bytes = 0
    for src, sub in ((args.mods, 'mods'), (args.romfs, 'RomFS'), (args.aoc, 'aoc'), (args.sysdata, 'sysdata')):
        if src:
            n, b = copy_tree(src, out / sub)
            total_files += n
            total_bytes += b

    link_or_copy(args.shaders, out / 'shaders.dmsv')
    total_files += 1
    total_bytes += args.shaders.stat().st_size
    if args.standard_font:
        shutil.copyfile(args.standard_font, out / 'standard.ttf')
    if args.ext_font:
        shutil.copyfile(args.ext_font, out / 'nintendo_ext.ttf')

    env = [
        f"DM_LANG={args.lang}",
        'DM_AUDIO_OHOS=1',
    ]
    (out / 'env.txt').write_text('\n'.join(env) + '\n', encoding='utf-8', newline='\n')

    manifest = {
        'title_id': TITLE_ID,
        'name': NAME,
        'package': args.package,
        'version': args.version,
        'display': args.display or args.version,
        'target': 'ohos',
        'language': args.lang,
        'requires': [],
        'files': total_files,
        'bytes': total_bytes,
        'dlc': sorted(int(p.name) for p in args.aoc.iterdir() if p.is_dir() and p.name.isdigit()) if args.aoc else [],
        'sysdata': sorted(p.name for p in args.sysdata.iterdir() if p.is_dir()) if args.sysdata else [],
        'made': time.strftime('%Y-%m-%d %H:%M:%S'),
    }
    (out / MANIFEST).write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'pack: {out}')
    print(f'  files: {total_files}')
    print(f'  bytes: {total_bytes} ({total_bytes / (1024 ** 3):.2f} GiB)')
    print(f'  title: {TITLE_ID} {NAME}')
    print(f'  shader: {args.shaders}')
    if args.zip:
        write_zip(out, args.zip)
        print('Import it in the app: UI -> 导入数据包（ZIP） -> select the archive, then restart.')
    else:
        print('Import it in the app: UI -> 导入数据包（文件夹） -> select this folder, then restart.')


if __name__ == '__main__':
    main()
